import { createClient } from '@supabase/supabase-js';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { extname, resolve } from 'node:path';

const BUCKET = process.env.VOCABULARY_IMAGE_BUCKET || 'english-vocabulary-images';
const MANIFEST_PATH = resolve('src/modules/english-vocabulary/image-manifest.generated.ts');
const MIME_TYPES = {
  '.jpeg': 'image/jpeg',
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
};

const sourceIndex = process.argv.indexOf('--source');
const sourceDirectory = sourceIndex >= 0 ? process.argv[sourceIndex + 1] : undefined;
const dryRun = process.argv.includes('--dry-run');

if (!sourceDirectory) {
  throw new Error('Thiếu thư mục ảnh. Ví dụ: npm run upload:vocabulary-images -- --source ./vocabulary-images');
}

const files = (await readdir(resolve(sourceDirectory), { withFileTypes: true }))
  .filter((entry) => entry.isFile() && MIME_TYPES[extname(entry.name).toLowerCase()])
  .map((entry) => entry.name)
  .sort();

for (const file of files) {
  const id = file.slice(0, -extname(file).length);
  if (!/^vocab-\d{3}$/.test(id)) {
    throw new Error(`Tên ảnh không hợp lệ: ${file}. Dùng định dạng vocab-001.webp.`);
  }
}

if (dryRun) {
  console.log(`Hợp lệ: ${files.length} ảnh sẽ được upload vào bucket ${BUCKET}.`);
  process.exit(0);
}

const supabaseUrl = process.env.SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!supabaseUrl || !serviceRoleKey) {
  throw new Error('Cần SUPABASE_URL và SUPABASE_SERVICE_ROLE_KEY trong môi trường của agent.');
}

const supabase = createClient(supabaseUrl, serviceRoleKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const { data: bucket, error: bucketError } = await supabase.storage.getBucket(BUCKET);
if (bucketError && bucketError.message !== 'Bucket not found') throw bucketError;
if (!bucket) {
  const { error } = await supabase.storage.createBucket(BUCKET, { public: true });
  if (error) throw error;
}

for (const file of files) {
  const extension = extname(file).toLowerCase();
  const body = await readFile(resolve(sourceDirectory, file));
  const { error } = await supabase.storage.from(BUCKET).upload(file, body, {
    contentType: MIME_TYPES[extension],
    cacheControl: '31536000',
    upsert: true,
  });
  if (error) throw new Error(`${file}: ${error.message}`);
}

const { data: objects, error: listError } = await supabase.storage.from(BUCKET).list('', {
  limit: 1000,
  sortBy: { column: 'name', order: 'asc' },
});
if (listError) throw listError;

const urls = Object.fromEntries(
  (objects ?? [])
    .filter((object) => MIME_TYPES[extname(object.name).toLowerCase()])
    .map((object) => {
      const id = object.name.slice(0, -extname(object.name).length);
      const { data } = supabase.storage.from(BUCKET).getPublicUrl(object.name);
      return [id, data.publicUrl];
    }),
);

const manifest = `// Generated by scripts/upload-vocabulary-images.mjs after images are uploaded.\nexport const vocabularyImageUrls: Readonly<Record<string, string>> = ${JSON.stringify(urls, null, 2)};\n`;
await writeFile(MANIFEST_PATH, manifest, 'utf8');
console.log(`Đã upload ${files.length} ảnh và ghi ${Object.keys(urls).length} URL vào manifest.`);
